    <h1>QUE RECUERDO DE JAVA</h1>
    <h2>SINTAXIS</h2>
    <p>Son las reglas obligatorias que se deben seguir para escribir un programa en Java sin cometer errores de sintaxis y q funcione bien.</p>
    <h2>Estrucuturas repetitivas</h2>
    <p>Son instrucciones que permiten repetir una misma tarea varias veces de forma automática mientras se cumpla una condición, evitando escribir el mismo código muchas veces.
        Los 3 tipos principales:
        -for: Se usa cuando sabes exactamente cuántas veces quieres repetir algo.
	    -while: Repite el código mientras una condición sea verdadera. Primero evalúa la condición y luego ejecuta.
	    -do-while: Ejecuta el código al menos una vez y después pregunta si la condición se cumple para seguir repitiendo.
    </p>
    <h2>Que es POO</h2>
    <p>La POO (Programación Orientada a Objetos) busca que programar sea más ordenado, agrupando datos y acciones dentro de un mismo paquete en lugar de tener código suelto.</p>
    <h2>Herencia</h2>
    <p>Es una característica de la POO que permite crear una clase hija aprovechando todo lo que ya tiene una clase padre. Su objetivo principal es reutilizar código y evitar repetir atributos o métodos para facilitar el trabajo</p>
