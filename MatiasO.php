Resumen de JAVA

 1. Sintaxis de JAVA
   Son las reglas y ortografia que se deve seguir para que el programa y la computadora entiendan nuestro 
   codigo teniendo que espicificar siempre el dato que usamos y prestar atencion a las mayusculas.
   Todo arranca desde el main y cada linea o instruccion termina con";", tambien se usan llaves "{}" 
   para agrupar bloques de codigo. Como ultimo se usan variables para gusardar tipos especificos de datos 
   como numeros enteros, decimales, texto, falso o verdadero, etc.
 2. Estructuras Repetitivas
   Son herramientas que sirven para repetir un bloque de codigo varias veces sin esforzarse en repetirlo 
   muchas veces.
   For: se usa cuando sabes exactamente cuantas veces quieres repetir algo.
   While: es cuando no sabes cuantas veces se repetira el ciclo pero si sabes que condicion debe mantenerse 
   verdadera para seguir.
 3. POO: Atributos y Metodos
   Consiste en programar pensando en objetos de la vida real, debemos crearlos con una clase y apartir de 
   eso los objetos.
   Atributos: Son las variavles que descruben como es el objeto.
   Metodos: Son las funciones que definen que puede hacer el objetos o sus acciones.
 4. Herencia
   permite crear una clase nueva basandose en una clase que ya existe para reutilizar codigo y evitar repetir
    atributos y metodos mas comunes.
   Superclase: Es la clase general donde se tienen los datos Basicos.
   Subclase: Es la clase hija que hereda todo lo del padre usando la palabra "extends" y ademas se agregan 
   sus caracteristicas propias.