    SINTAXIS
    La sintaxis de Java está formada por un conjunto de reglas que indican cómo debe
    escribirse el código para que el compilador pueda interpretarlo y ejecutarlo correctamente. Al igual que ocurre 
    con cualquier
    lenguaje de programación, cada instrucción debe respetar una estructura determinada. Si se comete un error al escribir una palabra
     reservada, colocar un símbolo o declarar una variable, el compilador puede generar un error e impedir que el programa se ejecute.

Java es un lenguaje fuertemente tipado, lo que significa que cada variable debe declararse indicando el tipo de 
dato que va a almacenar, como int, double, String o boolean. También distingue entre letras mayúsculas y minúsculas, por lo 
que nombre, Nombre y NOMBRE se consideran identificadores diferentes.

El código Java se organiza mediante clases. Las instrucciones normalmente terminan con punto y
 coma (;), mientras que las llaves ({}) permiten agrupar bloques de código, como el contenido de una clase, un método o una 
 estructura condicional. La ejecución de una aplicación Java tradicional comienza en el método main, que funciona como punto de 
 entrada del programa.

 ESTRUCTURAS REPETITIVAS

Las estructuras repetitivas, también conocidas como bucles o ciclos, permiten ejecutar varias veces un mismo bloque de instrucciones
 sin necesidad de escribirlo repetidamente. Se utilizan cuando una tarea debe realizarse varias veces, como recorrer una lista,
mostraruna serie de números o solicitar datos hasta que se cumpla determinada condición.

Java cuenta principalmente con tres estructuras repetitivas: for, while y do-while. Aunque las tres permiten repetir instrucciones,
 cada una tiene una forma distinta de controlar las iteraciones.

 EL FOR:

El bucle for se utiliza generalmente cuando se conoce la cantidad de veces que se desea repetir una operación. En su estructura 
se incluye una variable de control, una condición y una actualización que se ejecuta en cada vuelta.

EL WHILE:
Por otro lado, while permite repetir un bloque de instrucciones mientras una condición sea verdadera. A diferencia de for, suele
 utilizarse cuando no se conoce exactamente cuántas veces será necesario repetir una operación. La condición 
se evalúa antes de ejecutar el bloque, por lo que existe la posibilidad de que nunca llegue a ejecutarse.

EL DO-WHILE:
Finalmente, do-while tiene un funcionamiento parecido al de while, pero con una diferencia importante: primero ejecuta las instrucciones
y después comprueba la condición. Esto garantiza que el bloque se ejecute al menos una vez, incluso si la condición es falsa desde el 
principio.

 POO (Atributos y Métodos)
La Programación Orientada a Objetos (POO) es un paradigma que permite organizar un programa mediante clases y objetos. La idea consiste en 
representar elementos mediante estructuras que reúnen sus características y los comportamientos que pueden realizar.
Una clase funciona como una plantilla o modelo a partir del cual se crean los objetos. Por ejemplo, se puede definir una clase llamada 
Vehiculo y utilizarla para crear diferentes vehículos, cada uno con sus propios valores y características.

Dentro de una clase se encuentran los atributos y los métodos. Los atributos son variables que almacenan información sobre el objeto y 
representan su estado. Pueden describir características como el color, la marca, el tamaño o la velocidad.

Los métodos, en cambio, representan las acciones que puede realizar un objeto. Por ejemplo, un vehículo puede arrancar, acelerar o frenar.
 Estos comportamientos se definen mediante métodos que contienen las instrucciones necesarias para realizar cada operación.

