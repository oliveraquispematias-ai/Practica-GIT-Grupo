SINTAXIS DE JAVA
    La sintaxis de Java son el conjunto de reglas que debemos seguir para escribir correctamente el codigo.
    Algunas de sus características principales son:

    -Cada instrucción termina con punto y coma (;).
    -El método principal de un programa es public static void main(String[] args).
    -Se utilizan llaves { } para delimitar bloques de código.
    -Las variables deben tener un tipo de dato, como int, double, String
    -Los comentarios pueden escribirse con // o /* */.
ESTRUCTURA REPETITIVA

    Las estructuras repetitivas permiten ejecutar un bloque de instrucciones varias veces, dependiendo de una condición. Existen tres estructuras principales:
    -For: se utiliza cuando conocemos la cantidad de veces que queremos repetir el bucle.
    -While: repite un bloque de código mientras la condición sea verdadera.
    -Do While: ejecuta primero las instrucciones y después verifica la condición, por lo que se ejecuta al menos una vez.

POO 

    Programación Orientada a Objetos (POO) es una forma de programar que organiza el código mediante clases y objetos.
    Clase: es una plantilla o modelo que define las características y comportamientos de un objeto.
    Objeto: es una instancia de una clase.
    Atributos: son las variables o como dice su nombre, atributos que representan las características del objeto.
    Métodos: son las funciones o acciones que puede realizar el objeto elegido.

HERENCIA

    La herencia es uno de los conceptos principales de POO, Permite que una clase herede atributos y métodos de otra clase evitando repetir instrucciones.